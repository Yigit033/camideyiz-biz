package biz.camideyiz.app.adhan;

import android.app.Notification;
import android.app.NotificationChannel;
import android.app.NotificationManager;
import android.app.PendingIntent;
import android.content.Context;
import android.content.Intent;
import android.graphics.Color;
import android.os.Build;
import android.util.Log;

/**
 * When the full ezan REPLACES the prayer notification, the user must never
 * end up with nothing. Every path that cannot voice the ezan (late OS
 * delivery, silent/vibrate ringer, muted media, an ongoing call, a blocked
 * service start, playback error) posts an audible "X vakti girdi" instead.
 * After the ezan finishes or is stopped, a QUIET record replaces the
 * playback notification so the prayer entry stays visible in the shade.
 *
 * Channel ids are the ones expo-notifications creates for prayer reminders,
 * so users manage one consistent set of channels in Android settings.
 */
final class AdhanNotifier {
  static final String CHANNEL_AUDIBLE="namaz-hatirlatma-v2";
  static final String CHANNEL_QUIET="sessiz-namaz-hatirlatma-v2";
  private static final String TAG="CamideyizAdhan";
  private static final int BRAND_COLOR=Color.parseColor("#0C76B4");

  /** `detail` is shown in the collapsed notification itself, so the user
   * always sees WHY the ezan was not voiced and what to change. */
  enum Reason{
    LATE("Telefon vakti geç bildirdi; ezan yerine bildirim geldi."),
    SILENT("Telefon sessiz, titreşimde veya Rahatsız Etmeyin modundaydı."),
    MUTED("Alarm ses düzeyi kapalıydı."),
    BUSY("Telefon görüşmesi sürüyordu."),
    FAILED("Telefon ezanı başlatmaya izin vermedi."),
    COMPLETED("Ezan okundu."),
    STOPPED("Ezan durduruldu.");
    final String detail;
    Reason(String detail){this.detail=detail;}
    boolean audible(){return this!=COMPLETED&&this!=STOPPED;}
  }

  private AdhanNotifier(){}

  static int smallIcon(Context context){
    // Generated by the expo-notifications config plugin (brand silhouette).
    int id=context.getResources().getIdentifier("notification_icon","drawable",
        context.getPackageName());
    return id!=0?id:android.R.drawable.ic_lock_idle_alarm;
  }

  static void ensureChannels(Context context){
    if(Build.VERSION.SDK_INT<Build.VERSION_CODES.O)return;
    NotificationManager manager=context.getSystemService(NotificationManager.class);
    if(manager==null)return;
    // createNotificationChannel never overrides a user's existing choices.
    if(manager.getNotificationChannel(CHANNEL_AUDIBLE)==null){
      NotificationChannel audible=new NotificationChannel(CHANNEL_AUDIBLE,
          "Namaz vakti hatırlatmaları",NotificationManager.IMPORTANCE_HIGH);
      audible.setDescription("Namaz vaktinde veya seçtiğiniz süre öncesinde sistem sesli bildirim");
      audible.enableVibration(true);
      audible.setVibrationPattern(new long[]{0,180,100,180});
      manager.createNotificationChannel(audible);
    }
    if(manager.getNotificationChannel(CHANNEL_QUIET)==null){
      NotificationChannel quiet=new NotificationChannel(CHANNEL_QUIET,
          "Sessiz namaz vakti bildirimleri",NotificationManager.IMPORTANCE_DEFAULT);
      quiet.setDescription("Ses çıkarmadan namaz vakti bildirimi");
      quiet.setSound(null,null);
      quiet.enableVibration(false);
      manager.createNotificationChannel(quiet);
    }
  }

  static PendingIntent openApp(Context context,int requestCode){
    Intent launch=context.getPackageManager().getLaunchIntentForPackage(context.getPackageName());
    if(launch==null)return null;
    launch.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK|Intent.FLAG_ACTIVITY_CLEAR_TOP);
    return PendingIntent.getActivity(context,requestCode,launch,
        PendingIntent.FLAG_UPDATE_CURRENT|PendingIntent.FLAG_IMMUTABLE);
  }

  /** One stable notification per prayer instant: a fallback and a later
   * quiet record replace each other instead of stacking. */
  static int notificationId(String alarmId){
    return 0x41000000|(alarmId==null?0:alarmId.hashCode()&0x00FFFFFF);
  }

  static void prayerEntered(Context context,String alarmId,String label,String time,
      String place,Reason reason){
    try{
      ensureChannels(context);
      NotificationManager manager=(NotificationManager)
          context.getSystemService(Context.NOTIFICATION_SERVICE);
      if(manager==null)return;
      String prayer=label==null||label.trim().isEmpty()?"Namaz":label.trim();
      StringBuilder where=new StringBuilder();
      if(place!=null&&!place.trim().isEmpty())where.append(place.trim());
      if(time!=null&&time.matches("\\d{2}:\\d{2}")){
        if(where.length()>0)where.append(" · ");
        where.append(time);
      }
      String body=(where.length()>0?where+"\n":"")+reason.detail;
      Notification.Builder builder=Build.VERSION.SDK_INT>=Build.VERSION_CODES.O
          ?new Notification.Builder(context,reason.audible()?CHANNEL_AUDIBLE:CHANNEL_QUIET)
          :new Notification.Builder(context);
      builder.setSmallIcon(smallIcon(context))
          .setColor(BRAND_COLOR)
          .setContentTitle(prayer+" vakti girdi")
          // A fallback leads with its reason; a quiet record with place · time.
          .setContentText(reason.audible()||where.length()==0
              ?reason.detail:where.toString())
          .setStyle(new Notification.BigTextStyle().bigText(body))
          .setCategory(reason.audible()?Notification.CATEGORY_REMINDER:Notification.CATEGORY_STATUS)
          .setVisibility(Notification.VISIBILITY_PUBLIC)
          .setShowWhen(true)
          .setAutoCancel(true);
      if(Build.VERSION.SDK_INT<Build.VERSION_CODES.O){
        builder.setPriority(reason.audible()?Notification.PRIORITY_HIGH:Notification.PRIORITY_LOW);
        if(reason.audible())builder.setDefaults(Notification.DEFAULT_ALL);
      }
      PendingIntent open=openApp(context,notificationId(alarmId));
      if(open!=null)builder.setContentIntent(open);
      manager.notify(notificationId(alarmId),builder.build());
    }catch(Exception error){
      // POST_NOTIFICATIONS revoked or channel blocked by the user.
      Log.w(TAG,"Prayer-entered notification could not be posted",error);
    }
  }

  /** "Ezanı test et" runs the exact same checks as a real prayer; when one
   * blocks the ezan the test says so instead of playing anyway. */
  static void testBlocked(Context context,Reason reason){
    try{
      ensureChannels(context);
      NotificationManager manager=(NotificationManager)
          context.getSystemService(Context.NOTIFICATION_SERVICE);
      if(manager==null)return;
      Notification.Builder builder=Build.VERSION.SDK_INT>=Build.VERSION_CODES.O
          ?new Notification.Builder(context,CHANNEL_AUDIBLE)
          :new Notification.Builder(context);
      builder.setSmallIcon(smallIcon(context))
          .setColor(BRAND_COLOR)
          .setContentTitle("Ezan testi · ezan okunmadı")
          .setContentText(reason.detail)
          .setStyle(new Notification.BigTextStyle().bigText(reason.detail))
          .setCategory(Notification.CATEGORY_REMINDER)
          .setAutoCancel(true);
      PendingIntent open=openApp(context,748035);
      if(open!=null)builder.setContentIntent(open);
      manager.notify(748036,builder.build());
    }catch(Exception error){
      Log.w(TAG,"Test result notification could not be posted",error);
    }
  }
}
